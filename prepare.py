#!/usr/bin/env python3
"""SwiftLD: one-time setup for evaluate.py.

    python3 prepare.py            # build the reference, prepare datasets, record expected outputs + timings (~25 min)

Steps:
  1. Build the reference: vcftools v0.1.17 (commit 1c53c3c) from GitHub, compiled directly with g++ -O2
     (no autotools needed), building zlib from GitHub source if the system headers are missing.
     One upstream bug is patched before building: the LD code sizes its temp-file name buffer without room for
     the terminating NUL (`char tmpname[new_tmp.size()]` + strcpy). Hardened compilers (_FORTIFY_SOURCE, the
     default on Ubuntu) abort with "buffer overflow detected" on every --hap-r2/--geno-r2 run. The patch adds
     the missing byte and changes nothing else; see ext/vcftools_tmpname.patch after setup.
  2. Prepare the benchmark and holdout VCFs: real 1000 Genomes subsets shipped in data/ (sha256-pinned in
     gen_data.py) and synthetic sets generated by gen_data.py (fixed seeds).
  3. Run the reference on each dataset with its benchmark options; record sha256 of the .ld output, its size,
     its row count and the wall time (best of 3).
  4. Write bench/manifest.json (expected outputs, timings, environment, script hashes).
Re-running is safe: finished steps are skipped.
"""
import hashlib
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
EXT = ROOT / "ext"
BENCH = ROOT / "bench"
DATA = BENCH / "data"
SOLVER = ROOT / "solver"
VCFTOOLS_COMMIT = "1c53c3c73be141103069965403e655536dda9c87"   # tag v0.1.17
SRC = EXT / "vcftools" / "src" / "cpp"
REF = EXT / "ref" / "vcftools"
SCRIPT_FILES = ["prepare.py", "evaluate.py", "gen_data.py"]
CXXFLAGS = "-O2"            # autotools' default optimisation level for vcftools releases


def sh(cmd, **kw):
    print("+", cmd if isinstance(cmd, str) else " ".join(map(str, cmd)), flush=True)
    return subprocess.run(cmd, shell=isinstance(cmd, str), check=True, **kw)


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def ensure_numpy():
    try:
        import numpy  # noqa: F401
    except ImportError:
        r = subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", "numpy"])
        if r.returncode != 0:  # PEP 668 "externally managed" images
            sh([sys.executable, "-m", "pip", "install", "--quiet", "--break-system-packages", "numpy"])


def zlib_flags():
    """Return (cflags, ldflags) that make zlib usable; builds zlib from GitHub if the headers are missing."""
    EXT.mkdir(exist_ok=True)
    test = EXT / "zt.c"
    test.write_text("#include <zlib.h>\nint main(){return zlibVersion()[0]==0;}\n")
    if subprocess.run(["gcc", str(test), "-lz", "-o", str(EXT / "zt")], capture_output=True).returncode == 0:
        return "", ""
    inst = EXT / "zlib-install"
    if not (inst / "lib" / "libz.a").exists():
        print("system zlib headers missing; building zlib from GitHub source")
        if not (EXT / "zlib").exists():
            sh(["git", "clone", "-q", "--depth", "1", "https://github.com/madler/zlib.git", str(EXT / "zlib")])
        sh(f"./configure --static --prefix={inst} >/dev/null && make -s install", cwd=EXT / "zlib")
    return f"-I{inst / 'include'}", f"-L{inst / 'lib'}"


def build_reference():
    if REF.exists():
        return
    d = EXT / "vcftools"
    if not d.exists():
        sh(["git", "clone", "-q", "https://github.com/vcftools/vcftools.git", str(d)])
    sh(["git", "checkout", "-q", VCFTOOLS_COMMIT], cwd=d)
    n = 0
    for f in SRC.glob("*.cpp"):
        s = f.read_text()
        if "char tmpname[new_tmp.size()];" in s:
            n += s.count("char tmpname[new_tmp.size()];")
            f.write_text(s.replace("char tmpname[new_tmp.size()];", "char tmpname[new_tmp.size()+1];"))
    print(f"patched {n} tmpname buffers (upstream off-by-one)")
    (EXT / "vcftools_tmpname.patch").write_text(
        subprocess.run(["git", "diff"], cwd=d, capture_output=True, text=True).stdout)
    zc, zl = zlib_flags()
    obj = EXT / "ref"
    obj.mkdir(exist_ok=True)
    for c in ["bgzf.c", "knetfile.c"]:
        sh(f"gcc {CXXFLAGS} -w {zc} -c {SRC / c} -o {obj / c.replace('.c', '.o')}")
    sh(f"g++ {CXXFLAGS} -w {zc} -DPACKAGE_VERSION='\"0.1.17\"' -o {REF} {SRC}/*.cpp {obj}/bgzf.o {obj}/knetfile.o "
       f"{zl} -lz")
    out = subprocess.run([str(REF), "--version"], capture_output=True, text=True)
    assert "VCFtools (0.1.17)" in out.stdout + out.stderr, out.stdout + out.stderr
    # Sanity: two perfectly linked sites -> r^2 = 1; one independent pair -> a finite r^2 below 1.
    tiny = EXT / "tiny.vcf"
    rows = ["##fileformat=VCFv4.2", "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tA\tB\tC\tD",
            "1\t100\t.\tA\tC\t.\tPASS\t.\tGT\t0|1\t1|1\t0|0\t1|0",
            "1\t200\t.\tG\tT\t.\tPASS\t.\tGT\t0|1\t1|1\t0|0\t1|0",
            "1\t300\t.\tG\tT\t.\tPASS\t.\tGT\t1|1\t0|0\t0|1\t0|0"]
    tiny.write_text("\n".join(rows) + "\n")
    sh([str(REF), "--vcf", str(tiny), "--hap-r2", "--out", str(EXT / "tiny")], capture_output=True)
    lines = (EXT / "tiny.hap.ld").read_text().splitlines()
    assert lines[1].split("\t")[4] == "1", lines
    print("reference vcftools 0.1.17 built and passes the r^2 sanity check")


def dataset_path(name, spec):
    return DATA / (name + (".vcf.gz" if spec.get("gz") or spec.get("real") else ".vcf"))


def ld_suffix(args):
    return ".hap.ld" if "--hap-r2" in args else ".geno.ld"


def run_ref(path, args, prefix, reps=3):
    """Best-of-`reps` wall time of the reference (sync before each run, as evaluate.py does)."""
    cmd = [str(REF), "--gzvcf" if str(path).endswith(".gz") else "--vcf", str(path), *args, "--out", str(prefix)]
    times = []
    for _ in range(reps):
        for p in Path(prefix).parent.glob(Path(prefix).name + ".*"):
            p.unlink()
        os.sync()
        t0 = time.perf_counter()
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        times.append(time.perf_counter() - t0)
    return min(times)


def prepare_sets(specs, kind):
    import gen_data  # noqa: E402  (needs numpy)
    rows = []
    DATA.mkdir(parents=True, exist_ok=True)
    tmp = BENCH / "tmp"
    tmp.mkdir(exist_ok=True)
    for name, spec in specs.items():
        path = dataset_path(name, spec)
        if not path.exists():
            if spec.get("real"):
                src = ROOT / spec["real"]
                got = sha256_file(src)
                assert got == spec["sha256"], f"{src} sha256 {got} != pinned {spec['sha256']}"
                shutil.copy(src, path)
            else:
                t0 = time.perf_counter()
                shape = gen_data.write_dataset(spec, path)
                print(f"generated {name} {shape} in {time.perf_counter() - t0:.1f}s", flush=True)
        prefix = tmp / "ref"
        out = Path(str(prefix) + ld_suffix(spec["args"]))
        out.unlink(missing_ok=True)
        t1 = run_ref(path, spec["args"], prefix)
        with open(out, "rb") as f:
            n_rows = sum(1 for _ in f) - 1
        row = dict(name=name, kind=kind, real=bool(spec.get("real")), path=str(path.relative_to(ROOT)),
                   args=spec["args"], expected_sha256=sha256_file(out), expected_bytes=out.stat().st_size,
                   rows=n_rows, ref_s=round(t1, 4))
        out.unlink()
        print(json.dumps(row), flush=True)
        rows.append(row)
    shutil.rmtree(tmp, ignore_errors=True)
    return rows


def main():
    os.chdir(ROOT)
    ensure_numpy()
    sys.path.insert(0, str(ROOT))
    build_reference()
    threads = os.cpu_count() or 1
    manifest_path = BENCH / "manifest.json"
    if manifest_path.exists():
        print("bench/manifest.json exists; delete bench/ to regenerate")
    else:
        import gen_data
        dev = prepare_sets(gen_data.DEV_SPECS, "dev")
        hold = prepare_sets(gen_data.HOLDOUT_SPECS, "holdout")
        cpu, flags = "", ""
        try:
            info = open("/proc/cpuinfo").read().splitlines()
            cpu = next(l.split(":", 1)[1].strip() for l in info if l.startswith("model name"))
            flags = next(l.split(":", 1)[1].strip() for l in info if l.startswith("flags"))
        except Exception:
            pass
        manifest = dict(
            created=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            reference=dict(tool="vcftools", version="0.1.17", commit=VCFTOOLS_COMMIT,
                           build=f"g++ {CXXFLAGS} (direct, no autotools); tmpname off-by-one patched"),
            threads=threads, cpu=cpu,
            simd=[f for f in ["sse4_2", "popcnt", "avx2", "avx512f", "avx512_vpopcntdq", "bmi2"] if f in flags.split()],
            gcc=subprocess.run(["gcc", "--version"], capture_output=True, text=True).stdout.splitlines()[0],
            python=platform.python_version(),
            dev=dev, holdout=hold,
            scripts_sha256={f: sha256_file(ROOT / f) for f in SCRIPT_FILES},
        )
        manifest_path.write_text(json.dumps(manifest, indent=1))
        print(f"wrote {manifest_path}")
    print("prepare: done")


if __name__ == "__main__":
    main()
